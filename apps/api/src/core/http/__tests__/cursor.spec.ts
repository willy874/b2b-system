import { describe, expect, it } from 'vitest';

import { isCursorTimestamp } from '../cursor';

describe('isCursorTimestamp（keyset 游標的時間，docs/architecture/backend/09-file.md §6.1）', () => {
  it.each([
    ['微秒（資料庫的 to_char … US）', '2026-10-01T08:30:00.123456Z'],
    ['毫秒（toISOString 的退路）', '2026-10-01T08:30:00.123Z'],
    ['閏年的 2 月 29 日', '2024-02-29T00:00:00.000000Z'],
    ['西元 1 年', '0001-01-01T00:00:00.000Z'],
  ])('%s → 接受', (_label, value) => {
    expect(isCursorTimestamp(value)).toBe(true);
  });

  it.each([
    ['2 月 30 日（V8 會進位成 3 月 2 日）', '2026-02-30T00:00:00.000000Z'],
    ['平年的 2 月 29 日', '2026-02-29T00:00:00.000000Z'],
    ['24 點（V8 會進位成隔天）', '2026-10-01T24:00:00.000Z'],
    ['13 月', '2026-13-01T00:00:00.000Z'],
    ['只有年份', '2026'],
    ['只有一個數字', '0'],
    ['只有日期', '2026-10-01'],
    ['沒有小數秒', '2026-10-01T08:30:00Z'],
    ['小數秒不是 3 或 6 位', '2026-10-01T08:30:00.1234Z'],
    ['不是 UTC', '2026-10-01T08:30:00.123+08:00'],
    ['西元 0 年（Postgres 沒有）', '0000-01-01T00:00:00.000Z'],
    ['後面接了別的東西', '2026-10-01T08:30:00.123Z OR 1=1'],
    ['不是字串', 1_790_000_000_000],
  ])('%s → 拒絕', (_label, value) => {
    expect(isCursorTimestamp(value)).toBe(false);
  });
});
